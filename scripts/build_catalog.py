#!/usr/bin/env python3
"""Render reference/action-catalog.md from actions-condensed.json (ToolKit) merged with action-definitions.json (WorkflowKit)."""
import json
import sys
from collections import Counter
from pathlib import Path

ref = Path(sys.argv[1]) if len(sys.argv) > 1 else Path(__file__).resolve().parent.parent / "reference"
tool = json.loads((ref / "actions-condensed.json").read_text(encoding="utf-8"))
defs_path = ref / "action-definitions.json"
defs = json.loads(defs_path.read_text(encoding="utf-8")) if defs_path.exists() else {}
os_txt = (ref / "os-version.txt").read_text(encoding="utf-8") if (ref / "os-version.txt").exists() else ""
meta_path = ref / "workflowkit-meta.json"
meta = json.loads(meta_path.read_text(encoding="utf-8")) if meta_path.exists() else {}


def loc(v):
    return v.get("__localized__", "") if isinstance(v, dict) else (v or "")


def param_class(identifier, key):
    for p in defs.get(identifier, {}).get("Parameters", []) or []:
        if p.get("Key") == key:
            return p.get("Class")
    return None


ids = sorted(set(tool) | set(defs), key=lambda i: (loc(defs.get(i, {}).get("Name")) or tool.get(i, {}).get("name") or i).lower())
kinds = Counter(tool[i].get("type") for i in tool)
only_defs = [i for i in ids if i not in tool]

out = [
    "# SignCut — Apple Shortcuts action catalog", "",
    "> Human-readable rendering of `actions-condensed.json` (Apple Shortcuts **ToolKit**) merged with",
    "> `action-definitions.json` (Apple's **WorkflowKit** classic action definitions, which also include the",
    "> control-flow actions). Generated by `scripts/build_catalog.py`; do not edit by hand.",
    f"> Source OS: {' '.join(os_txt.split())}" + (f"; current Shortcuts client version {meta['current_client_version']}" if meta.get("current_client_version") else ""),
    "", "For how these are written into a `.shortcut` plist (menus, If, Repeat, variables), read `control-flow-and-serialization.md`.", "",
    "## Coverage", "",
    f"- ToolKit records: **{len(tool)}** ({', '.join(f'{k}: {v}' for k, v in sorted(kinds.items()))})",
    f"- WorkflowKit classic definitions: **{len(defs)}**",
    f"- Present only in the WorkflowKit definitions (e.g. control flow): **{len(only_defs)}** — " + ", ".join(f"`{i}`" for i in only_defs), "",
]
for ident in ids:
    t, d = tool.get(ident, {}), defs.get(ident, {})
    name = loc(d.get("Name")) or t.get("name") or ident
    out += [f"### {name}", "", f"**Identifier:** `{ident}`  ", f"**Type:** `{t.get('type', 'workflowkit-definition')}`"
            + (f"  \n**Action class:** `{d['ActionClass']}`" if d.get("ActionClass") else ""), ""]
    summary = loc((d.get("Description") or {}).get("DescriptionSummary")) or t.get("description", "")
    if summary:
        out += [summary, ""]
    if t.get("deprecated"):
        out += [f"**Deprecated** — use `{t.get('replacedBy')}`.", ""]
    if t.get("parameters"):
        out.append("**Parameters:**\n")
        for p in t["parameters"]:
            cls = param_class(ident, p["key"])
            line = f"- `{p['key']}` — **{p.get('label', '')}**"
            if p.get("type"):
                line += f" (`{p['type']}`)"
            if cls:
                line += f" — serialization class `{cls}`"
            out.append(line)
            if p.get("description"):
                out.append(f"  - {p['description']}")
            if p.get("enumValues"):
                out.append("  - Available enum cases (value → title):")
                out += [f"    - `{e['value']}` → {e['title']}" for e in p["enumValues"]]
        out.append("")
    elif d.get("Parameters"):
        out.append("**Parameters (WorkflowKit definition):**\n")
        for p in d["Parameters"]:
            out.append(f"- `{p.get('Key')}` — **{loc(p.get('Label'))}** — serialization class `{p.get('Class')}`")
        out.append("")
    if (d.get("Input") or {}).get("ParameterKey"):
        out += [f"Input parameter key: `{d['Input']['ParameterKey']}`", ""]
    if t.get("outputName") or t.get("outputs"):
        out += [f"**Output:** {t.get('outputName', '')} {t.get('outputs', '')}".rstrip(), ""]
(ref / "action-catalog.md").write_text("\n".join(out) + "\n", encoding="utf-8")
print(f"wrote {ref / 'action-catalog.md'} ({len(ids)} entries)")
